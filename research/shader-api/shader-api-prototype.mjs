#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";

const fixtureUrl = new URL("./fixtures/custom-shader-materials.json", import.meta.url);
const fixture = JSON.parse(readFileSync(fixtureUrl, "utf8"));
const jsonMode = process.argv.includes("--json");

const scalarTypes = new Set(["float", "int", "bool"]);
const vectorTypes = new Set(["vec2", "vec3", "vec4"]);
const matrixTypes = new Set(["mat4"]);
const textureTypes = new Set(["texture2d"]);
const supportedUniformTypes = new Set([
  ...scalarTypes,
  ...vectorTypes,
  ...matrixTypes,
  ...textureTypes,
]);

const geometryAttributes = {
  box: {
    position: "vec3",
    normal: "vec3",
  },
  gltf: {
    position: "vec3",
    normal: "vec3",
    uv0: "vec2",
  },
  indexed: {
    position: "vec3",
    normal: "vec3",
    uv0: "vec2",
    color: "vec4",
  },
};

const capabilitySnapshots = {
  dualBackend: {
    backends: new Set(["webgl2", "webgpu"]),
    features: new Set([
      "indexed-geometry",
      "instancing",
      "readback-buffer",
      "storage-buffer",
      "texture-asset",
      "uint32-indices",
    ]),
    limits: {
      fragmentTextureUnits: 8,
    },
  },
  webgl2Only: {
    backends: new Set(["webgl2"]),
    features: new Set([
      "indexed-geometry",
      "instancing",
      "readback-buffer",
      "texture-asset",
      "uint32-indices",
    ]),
    limits: {
      fragmentTextureUnits: 8,
    },
  },
};

const portableForbiddenTokens = [
  {
    pattern: /\bgl_[A-Za-z0-9_]+\b/,
    reason: "GLSL built-in names are backend-specific",
  },
  {
    pattern: /\b(attribute|varying|uniform)\b/,
    reason: "GLSL declarations are generated by the renderer",
  },
  {
    pattern: /\bsampler2D\b/,
    reason: "texture bindings must use typed texture2d uniforms",
  },
  {
    pattern: /\btexture2D\s*\(/,
    reason: "texture sampling syntax is backend-specific",
  },
  {
    pattern: /@\s*(vertex|fragment|group|binding)\b/,
    reason: "WGSL attributes are backend-specific",
  },
  {
    pattern: /\bvar<[^>]+>/,
    reason: "WGSL address spaces are backend-specific",
  },
];

const results = fixture.cases.map((testCase) => {
  const capabilities = capabilitySnapshots[testCase.capabilities];
  if (capabilities === undefined) {
    return {
      name: testCase.name,
      pass: false,
      failures: [`unknown capability snapshot: ${testCase.capabilities}`],
    };
  }

  const validation = validateShaderMaterial(testCase.descriptor, capabilities);
  return {
    name: testCase.name,
    ...validation,
    pass: true,
    failures: [],
    expect: testCase.expect,
  };
});

const resultByName = new Map(results.map((result) => [result.name, result]));

for (const result of results) {
  if (result.expect === undefined) continue;

  if (result.status !== result.expect.status) {
    result.pass = false;
    result.failures.push(
      `expected status ${result.expect.status}, received ${result.status}`,
    );
  }

  const codes = new Set(result.diagnostics?.map((diagnostic) => diagnostic.code) ?? []);
  for (const expectedCode of result.expect.codes ?? []) {
    if (!codes.has(expectedCode)) {
      result.pass = false;
      result.failures.push(`missing diagnostic code ${expectedCode}`);
    }
  }

  if (result.expect.sameProgramCacheKeyAs !== undefined) {
    const other = resultByName.get(result.expect.sameProgramCacheKeyAs);
    if (other === undefined) {
      result.pass = false;
      result.failures.push(
        `unknown sameProgramCacheKeyAs reference ${result.expect.sameProgramCacheKeyAs}`,
      );
    } else if (result.programCacheKey !== other.programCacheKey) {
      result.pass = false;
      result.failures.push(
        `programCacheKey differs from ${result.expect.sameProgramCacheKeyAs}`,
      );
    }
  }

  if (result.expect.differentMaterialInstanceKeyFrom !== undefined) {
    const other = resultByName.get(result.expect.differentMaterialInstanceKeyFrom);
    if (other === undefined) {
      result.pass = false;
      result.failures.push(
        `unknown differentMaterialInstanceKeyFrom reference ${result.expect.differentMaterialInstanceKeyFrom}`,
      );
    } else if (result.materialInstanceKey === other.materialInstanceKey) {
      result.pass = false;
      result.failures.push(
        `materialInstanceKey unexpectedly matches ${result.expect.differentMaterialInstanceKeyFrom}`,
      );
    }
  }
}

const report = {
  apiVersion: fixture.apiVersion,
  cases: results.map(({ expect, ...result }) => result),
  passed: results.filter((result) => result.pass).length,
  failed: results.filter((result) => !result.pass).length,
};

if (jsonMode) {
  console.log(JSON.stringify(report, null, 2));
} else {
  for (const result of results) {
    const codes = result.diagnostics.map((diagnostic) => diagnostic.code);
    const key = result.programCacheKey === null
      ? "no-program-key"
      : result.programCacheKey.slice(0, 16);
    const suffix = codes.length === 0 ? "" : ` [${codes.join(", ")}]`;
    console.log(`${result.pass ? "PASS" : "FAIL"} ${result.name}: ${result.status} ${key}${suffix}`);
    for (const failure of result.failures) {
      console.log(`  - ${failure}`);
    }
  }
  console.log(`shader-api prototype validation: ${report.passed} passed, ${report.failed} failed`);
}

if (report.failed > 0) {
  process.exitCode = 1;
}

function validateShaderMaterial(descriptor, capabilities) {
  const diagnostics = [];

  if (descriptor?.kind !== "custom-shader-material") {
    diagnostics.push(error("shader_descriptor_invalid", "descriptor.kind must be custom-shader-material"));
  }

  const fallbackValid = validateFallbackMaterial(descriptor?.fallback, diagnostics);
  validateAttributes(descriptor, diagnostics);
  validateUniforms(descriptor, diagnostics);
  validateSnippets(descriptor, diagnostics);

  const gateDiagnostics = evaluateCapabilityGates(descriptor, capabilities);
  diagnostics.push(...gateDiagnostics);

  const hasErrors = diagnostics.some((diagnostic) => diagnostic.severity === "error");
  const hasGateMiss = gateDiagnostics.length > 0;
  const status = hasErrors
    ? "invalid"
    : hasGateMiss
      ? fallbackValid ? "fallback" : "invalid"
      : "custom";

  return {
    diagnostics,
    materialInstanceKey: hasErrors ? null : materialInstanceKey(descriptor),
    programCacheKey: hasErrors ? null : programCacheKey(descriptor),
    status,
  };
}

function validateFallbackMaterial(fallback, diagnostics) {
  if (fallback === undefined || fallback === null) {
    diagnostics.push(error("shader_fallback_missing", "custom shader materials require a built-in fallback material"));
    return false;
  }

  if (fallback.kind === "custom-shader") {
    diagnostics.push(error("shader_fallback_recursive", "fallback material must be built-in for v1"));
    return false;
  }

  if (!["standard", "unlit", "wireframe"].includes(fallback.kind)) {
    diagnostics.push(error("shader_fallback_invalid", `unsupported fallback material kind: ${String(fallback.kind)}`));
    return false;
  }

  if (!isTextureRef(fallback.baseColor)) {
    diagnostics.push(error("shader_fallback_invalid", "fallback material requires a valid baseColor texture reference"));
    return false;
  }

  return true;
}

function validateAttributes(descriptor, diagnostics) {
  const targets = descriptor?.geometryTargets ?? ["box"];
  const attributes = descriptor?.attributes ?? {};

  for (const target of targets) {
    if (geometryAttributes[target] === undefined) {
      diagnostics.push(error("shader_geometry_target_unsupported", `unsupported geometry target: ${String(target)}`));
    }
  }

  for (const [name, attribute] of Object.entries(attributes)) {
    if (!attribute || typeof attribute !== "object") {
      diagnostics.push(error("shader_attribute_invalid", `attribute ${name} must be an object`));
      continue;
    }
    if (typeof attribute.semantic !== "string") {
      diagnostics.push(error("shader_attribute_invalid", `attribute ${name} requires a semantic`));
      continue;
    }
    if (!isShaderValueType(attribute.type)) {
      diagnostics.push(error("shader_attribute_invalid", `attribute ${name} has unsupported type ${String(attribute.type)}`));
      continue;
    }

    if (attribute.required !== true) continue;

    for (const target of targets) {
      const available = geometryAttributes[target];
      if (available === undefined) continue;
      const suppliedType = available[attribute.semantic];
      if (suppliedType === undefined) {
        diagnostics.push(error(
          "shader_attribute_unsupported",
          `required attribute ${name} (${attribute.semantic}) is unavailable on ${target} geometry`,
          { attribute: name, geometryTarget: target, semantic: attribute.semantic },
        ));
      } else if (suppliedType !== attribute.type) {
        diagnostics.push(error(
          "shader_attribute_unsupported",
          `required attribute ${name} expects ${attribute.type}, but ${target}.${attribute.semantic} supplies ${suppliedType}`,
          { attribute: name, geometryTarget: target, semantic: attribute.semantic },
        ));
      }
    }
  }

  const uses = descriptor?.snippets?.vertex?.uses ?? [];
  for (const attributeName of uses) {
    if (attributes[attributeName] === undefined) {
      diagnostics.push(error(
        "shader_attribute_undeclared",
        `vertex snippet uses undeclared attribute ${String(attributeName)}`,
        { attribute: attributeName },
      ));
    }
  }
}

function validateUniforms(descriptor, diagnostics) {
  const uniforms = descriptor?.uniforms ?? {};

  for (const [name, uniform] of Object.entries(uniforms)) {
    if (!uniform || typeof uniform !== "object") {
      diagnostics.push(error("shader_uniform_invalid", `uniform ${name} must be an object`));
      continue;
    }
    if (!supportedUniformTypes.has(uniform.type)) {
      diagnostics.push(error("shader_uniform_invalid", `uniform ${name} has unsupported type ${String(uniform.type)}`));
      continue;
    }

    if (!matchesUniformType(uniform.type, uniform.default)) {
      diagnostics.push(error(
        "shader_uniform_type_mismatch",
        `uniform ${name} default does not match ${uniform.type}`,
        { uniform: name, type: uniform.type, value: uniform.default },
      ));
    }
  }

  for (const [name, value] of Object.entries(descriptor?.runtimeUniforms ?? {})) {
    const uniform = uniforms[name];
    if (uniform === undefined) {
      diagnostics.push(error("shader_uniform_unknown", `runtime uniform ${name} is not declared`));
      continue;
    }
    if (!matchesUniformType(uniform.type, value)) {
      diagnostics.push(error(
        "shader_uniform_type_mismatch",
        `runtime uniform ${name} does not match ${uniform.type}`,
        { uniform: name, type: uniform.type, value },
      ));
    }
  }
}

function validateSnippets(descriptor, diagnostics) {
  const snippets = descriptor?.snippets;
  if (snippets === undefined || snippets === null) {
    diagnostics.push(error("shader_snippet_missing", "custom shader material requires snippets"));
    return;
  }

  if (snippets.language !== "royal-shader-v1") {
    diagnostics.push(error("shader_language_unsupported", `unsupported shader language ${String(snippets.language)}`));
  }

  const vertex = snippets.vertex;
  const fragment = snippets.fragment;
  if (vertex === undefined || fragment === undefined) {
    diagnostics.push(error("shader_snippet_missing", "custom shader material requires vertex and fragment snippets"));
    return;
  }

  if (snippets.portability === "webgl2-webgpu") {
    validatePortableSource("vertex", vertex.code ?? "", diagnostics);
    validatePortableSource("fragment", fragment.code ?? "", diagnostics);
  }

  compileSnippet("vertex", vertex.code, diagnostics);
  compileSnippet("fragment", fragment.code, diagnostics);
  linkSnippets(vertex.outputs ?? {}, fragment.inputs ?? {}, diagnostics);
}

function validatePortableSource(stage, source, diagnostics) {
  for (const token of portableForbiddenTokens) {
    const match = source.match(token.pattern);
    if (match !== null) {
      diagnostics.push(error(
        "shader_portability_violation",
        `${stage} snippet uses backend-specific token "${match[0]}": ${token.reason}`,
        { stage, token: match[0] },
      ));
    }
  }
}

function compileSnippet(stage, source, diagnostics) {
  if (typeof source !== "string" || source.trim() === "") {
    diagnostics.push(error("shader_compile_error", `${stage} snippet is empty`, { stage }));
    return;
  }
  if (!source.includes("return")) {
    diagnostics.push(error("shader_compile_error", `${stage} snippet must return a value`, { stage }));
  }
  if (source.includes("SYNTAX_ERROR")) {
    diagnostics.push(error("shader_compile_error", `${stage} snippet contains a syntax error marker`, { stage }));
  }

  for (const delimiter of [
    ["(", ")"],
    ["[", "]"],
    ["{", "}"],
  ]) {
    if (!balanced(source, delimiter[0], delimiter[1])) {
      diagnostics.push(error(
        "shader_compile_error",
        `${stage} snippet has unbalanced ${delimiter[0]}${delimiter[1]} delimiters`,
        { stage },
      ));
    }
  }
}

function linkSnippets(vertexOutputs, fragmentInputs, diagnostics) {
  for (const [name, type] of Object.entries(fragmentInputs)) {
    const vertexType = vertexOutputs[name];
    if (vertexType === undefined) {
      diagnostics.push(error(
        "shader_link_error",
        `fragment input ${name} is not written by the vertex snippet`,
        { input: name },
      ));
    } else if (vertexType !== type) {
      diagnostics.push(error(
        "shader_link_error",
        `fragment input ${name} expects ${type}, but vertex output is ${vertexType}`,
        { input: name },
      ));
    }
  }
}

function evaluateCapabilityGates(descriptor, capabilities) {
  const diagnostics = [];
  const gates = descriptor?.gates ?? {};
  const requestedBackends = gates.backends ?? ["webgl2"];
  const requestedFeatures = gates.features ?? [];

  const backendAvailable = requestedBackends.some((backend) => capabilities.backends.has(backend));
  if (!backendAvailable) {
    diagnostics.push(warning(
      "renderer_backend_unavailable",
      `none of the requested backends are available: ${requestedBackends.join(", ")}`,
      { requestedBackends },
    ));
  }

  for (const feature of requestedFeatures) {
    if (!capabilities.features.has(feature)) {
      diagnostics.push(warning(
        "renderer_feature_unavailable",
        `required renderer feature is unavailable: ${feature}`,
        { feature },
      ));
    }
  }

  const textureUniformCount = Object.values(descriptor?.uniforms ?? {})
    .filter((uniform) => uniform?.type === "texture2d")
    .length;
  const requestedTextureUnits = gates.limits?.fragmentTextureUnits ?? textureUniformCount;
  if (requestedTextureUnits > capabilities.limits.fragmentTextureUnits) {
    diagnostics.push(warning(
      "renderer_limit_unavailable",
      `requires ${requestedTextureUnits} fragment texture units, but renderer has ${capabilities.limits.fragmentTextureUnits}`,
      {
        available: capabilities.limits.fragmentTextureUnits,
        requested: requestedTextureUnits,
      },
    ));
  }

  return diagnostics;
}

function programCacheKey(descriptor) {
  const uniformTypes = {};
  for (const [name, uniform] of Object.entries(descriptor.uniforms ?? {})) {
    uniformTypes[name] = { type: uniform.type };
  }

  const canonical = {
    apiVersion: fixture.apiVersion,
    attributes: descriptor.attributes ?? {},
    gates: {
      backends: sortedStrings(descriptor.gates?.backends ?? ["webgl2"]),
      features: sortedStrings(descriptor.gates?.features ?? []),
      limits: descriptor.gates?.limits ?? {},
    },
    geometryTargets: sortedStrings(descriptor.geometryTargets ?? ["box"]),
    id: descriptor.id,
    revision: descriptor.revision ?? null,
    snippets: canonicalSnippets(descriptor.snippets),
    uniforms: uniformTypes,
  };

  return hashStable(canonical);
}

function materialInstanceKey(descriptor) {
  return hashStable({
    fallback: descriptor.fallback,
    programCacheKey: programCacheKey(descriptor),
    runtimeUniforms: descriptor.runtimeUniforms ?? {},
    uniformDefaults: Object.fromEntries(
      Object.entries(descriptor.uniforms ?? {}).map(([name, uniform]) => [
        name,
        uniform.default,
      ]),
    ),
  });
}

function canonicalSnippets(snippets) {
  if (snippets === undefined || snippets === null) return null;
  return {
    fragment: {
      code: snippets.fragment?.code ?? "",
      inputs: snippets.fragment?.inputs ?? {},
    },
    language: snippets.language ?? null,
    portability: snippets.portability ?? null,
    vertex: {
      code: snippets.vertex?.code ?? "",
      outputs: snippets.vertex?.outputs ?? {},
      uses: sortedStrings(snippets.vertex?.uses ?? []),
    },
  };
}

function matchesUniformType(type, value) {
  switch (type) {
    case "float":
      return isFiniteNumber(value);
    case "int":
      return Number.isInteger(value);
    case "bool":
      return typeof value === "boolean";
    case "vec2":
      return isNumberArray(value, 2);
    case "vec3":
      return isNumberArray(value, 3);
    case "vec4":
      return isNumberArray(value, 4);
    case "mat4":
      return isNumberArray(value, 16);
    case "texture2d":
      return isTextureRef(value);
    default:
      return false;
  }
}

function isShaderValueType(type) {
  return scalarTypes.has(type) || vectorTypes.has(type) || matrixTypes.has(type);
}

function isTextureRef(value) {
  if (value === undefined || value === null || typeof value !== "object") return false;
  if (value.kind === "solid") return isNumberArray(value.color, 4);
  if (value.kind === "asset") {
    return typeof value.id === "string"
      && typeof value.uri === "string"
      && (value.fallback === undefined || isTextureRef(value.fallback));
  }
  return false;
}

function isNumberArray(value, length) {
  return Array.isArray(value)
    && value.length === length
    && value.every((entry) => isFiniteNumber(entry));
}

function isFiniteNumber(value) {
  return typeof value === "number" && Number.isFinite(value);
}

function balanced(source, open, close) {
  let depth = 0;
  for (const char of source) {
    if (char === open) depth += 1;
    if (char === close) depth -= 1;
    if (depth < 0) return false;
  }
  return depth === 0;
}

function warning(code, message, detail = undefined) {
  return diagnostic("warning", code, message, detail);
}

function error(code, message, detail = undefined) {
  return diagnostic("error", code, message, detail);
}

function diagnostic(severity, code, message, detail) {
  return {
    code,
    ...(detail === undefined ? {} : { detail }),
    message,
    severity,
  };
}

function hashStable(value) {
  return createHash("sha256")
    .update(stableStringify(value))
    .digest("hex");
}

function stableStringify(value) {
  if (value === null || typeof value !== "object") return JSON.stringify(value);
  if (Array.isArray(value)) return `[${value.map(stableStringify).join(",")}]`;

  const entries = Object.entries(value)
    .filter(([, entry]) => entry !== undefined)
    .sort(([left], [right]) => left.localeCompare(right));
  return `{${entries.map(([key, entry]) => `${JSON.stringify(key)}:${stableStringify(entry)}`).join(",")}}`;
}

function sortedStrings(values) {
  return [...values].map(String).sort((left, right) => left.localeCompare(right));
}
